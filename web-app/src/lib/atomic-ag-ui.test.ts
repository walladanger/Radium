import { describe, expect, it, vi } from 'vitest'
import { AtomicAgUiProjection } from './atomic-ag-ui'
import type { ControlSnapshot } from './atomic-control'
const snapshot = (sequence: number): ControlSnapshot => ({ schema_version: 1, sequence, plans: [], tasks: [], attempts: [], workers: [], approvals: [], artifacts: [], candidates: [] })
const event = { sequence: 4, event_id: 'event-4', event_type: 'agent_progress', created_at: 12, payload: { task_id: 'task', attempt_id: 'attempt', stage: 'tool', step_index: 2, worker_id: 'worker', service_id: 'gpu0', model: 'local', reasoning: 'private', permission: 'allow' } }
describe('optional AG-UI state projection', () => {
  it.each(['preparing_tool', 'awaiting_checks', 'agent_stopped'])('projects the observed %s stage without private payloads', stage => {
    const projection = new AtomicAgUiProjection()
    const receive = vi.fn()
    projection.subscribe(receive)
    projection.setEnabled(true, snapshot(3))
    projection.publishEvent({ ...event, payload: { ...event.payload, stage } })
    expect(receive.mock.calls[1][0].value.stage).toBe(stage)
    expect(JSON.stringify(receive.mock.calls)).not.toContain('private')
  })
  it('defaults off and enabling emits current state without commands or lifecycle fiction', () => {
    const projection = new AtomicAgUiProjection()
    const receive = vi.fn()
    projection.subscribe(receive)
    projection.publishSnapshot(snapshot(3))
    projection.publishEvent(event)
    expect(receive).not.toHaveBeenCalled()
    projection.setEnabled(true, snapshot(3))
    expect(receive).toHaveBeenCalledWith({ type: 'STATE_SNAPSHOT', snapshot: { atomicControl: snapshot(3) } })
    projection.publishEvent(event)
    expect(receive).toHaveBeenLastCalledWith({ type: 'CUSTOM', timestamp: 12, name: 'atomic.control.transition', value: { sequence: 4, eventId: 'event-4', eventType: 'agent_progress', taskId: 'task', attemptId: 'attempt', stage: 'tool', stepIndex: 2, workerId: 'worker', serviceId: 'gpu0', model: 'local' } })
  })
  it('deduplicates replay, isolates consumers and removes unknown/private fields', () => {
    const projection = new AtomicAgUiProjection()
    projection.subscribe(() => { throw new Error('broken extension') })
    projection.subscribe(value => { if (value.type === 'STATE_SNAPSHOT') value.snapshot.atomicControl.sequence = 999 })
    const receive = vi.fn()
    projection.subscribe(receive)
    const source = snapshot(3)
    source.tasks.push({ id: 't', plan_id: 'p', title: 'Work', description: '', role: 'edit', dependencies: [], write_scopes: [], revision: 1, status: 'ready', created_at: 1, reasoning: 'private' })
    projection.setEnabled(true, source)
    expect(JSON.stringify(receive.mock.calls)).not.toContain('private')
    expect(source.sequence).toBe(3)
    expect(receive.mock.calls[0][0].snapshot.atomicControl.sequence).toBe(3)
    projection.publishSnapshot(snapshot(3))
    projection.publishEvent(event)
    projection.publishEvent(event)
    expect(receive).toHaveBeenCalledTimes(2)
    projection.setEnabled(false, source)
    projection.publishSnapshot(snapshot(5))
    projection.publishEvent({ ...event, sequence: 5 })
    expect(receive).toHaveBeenCalledTimes(2)
    projection.setEnabled(true, snapshot(5))
    expect(receive).toHaveBeenCalledTimes(3)
  })
})
